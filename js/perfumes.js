// ----------------------------------------------
//  CATÁLOGO
//  P(nombre, inspiración, género, categoría, familia, propósitos, notas, acordes, destacado)
//   - propósitos: ids separados por espacio (diario seduccion eventos deporte regalo)
//   - notas: "salida | corazón | fondo"
//   - acordes: "Acorde %, Acorde %, ..." (los nombres deben existir en ACORDES)
//   - destacado: true para que salga primero y con la etiqueta Favorito
//   - foto: agrega .imagen = "img/archivo.webp" después, si quieres (ver final del archivo)
// ----------------------------------------------
